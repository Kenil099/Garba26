CREATE TABLE IF NOT EXISTS songs (
    id INTEGER PRIMARY KEY AUTOINCREMENT,
    title VARCHAR(200) NOT NULL,
    slug VARCHAR(200) NOT NULL,
    artist_id INTEGER NOT NULL,
    album_id INTEGER NULL,
    genre_id INTEGER NULL,
    duration INTEGER DEFAULT 210,
    audio_url VARCHAR(255) DEFAULT '',
    cover_image VARCHAR(255) DEFAULT '/assets/images/default-album.png',
    style VARCHAR(100) DEFAULT '3-Taali',
    era VARCHAR(100) DEFAULT 'Modern',
    tradition VARCHAR(100) DEFAULT 'United Way',
    lyrics TEXT NULL,
    plays_count INTEGER DEFAULT 0,
    is_featured INTEGER DEFAULT 0,
    is_popular INTEGER DEFAULT 0,
    created_at DATETIME DEFAULT CURRENT_TIMESTAMP,
    updated_at DATETIME DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (artist_id) REFERENCES artists(id) ON DELETE CASCADE,
    FOREIGN KEY (album_id) REFERENCES albums(id) ON DELETE SET NULL,
    FOREIGN KEY (genre_id) REFERENCES genres(id) ON DELETE SET NULL
);
